package com.example.banking.service;

import com.example.banking.model.Audit;
import com.example.banking.model.User;
import com.example.banking.repository.AuditRepository;
import com.example.banking.repository.UserRepository;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import java.math.BigDecimal;

import java.util.List;
import java.util.Optional;

@Service
public class UserService {
    @Autowired
    private UserRepository userRepository;
    @Autowired
    private AuditRepository auditRepository;
    @Autowired
    private ObjectMapper objectMapper;

    public List<User> getAllUsers() {
        try {
            List<User> users = userRepository.findAll();
            System.out.println("UserService: Found " + users.size() + " users in the database");
            return users;
        } catch (Exception e) {
            System.err.println("Error fetching users: " + e.getMessage());
            throw e;
        }
    }

    public Optional<User> getUser(Long id) {
        return userRepository.findById(id);
    }

    public User createUser(User user) {
        try {
            System.out.println("=== UserService: Creating new user ===");
            System.out.println("User details before save: " + user);
            
            // Ensure credit limit is a BigDecimal
            if (user.getCreditLimit() == null) {
                user.setCreditLimit(BigDecimal.ZERO);
            }
            
            // Save the user (account number will be auto-generated by @PrePersist)
            User savedUser = userRepository.save(user);
            System.out.println("=== UserService: User created successfully ===");
            System.out.println("Saved user details: " + savedUser);
            
            // TODO: Fix audit entry creation - temporarily disabled due to JSONB issues
            // auditRepository.save(new Audit(null, savedUser.getId(), "CREATE", null, toJson(savedUser), null));
            
            return savedUser;
        } catch (Exception e) {
            System.err.println("=== UserService: Error creating user ===");
            System.err.println("Error: " + e.getMessage());
            e.printStackTrace();
            throw new RuntimeException("Failed to create user: " + e.getMessage(), e);
        }
    }

    public User updateUser(Long id, User userDetails) {
        User user = userRepository.findById(id).orElseThrow();
        String oldData = toJson(user);
        user.setName(userDetails.getName());
        user.setAddress(userDetails.getAddress());
        user.setCreditLimit(userDetails.getCreditLimit());
        User updated = userRepository.save(user);
        // TODO: Fix audit creation - temporarily disabled
        // auditRepository.save(new Audit(null, id, "UPDATE", oldData, toJson(updated), null));
        return updated;
    }

    public void deleteUser(Long id) {
        try {
            System.out.println("=== UserService: Attempting to delete user with ID: " + id + " ===");
            User user = userRepository.findById(id)
                .orElseThrow(() -> new RuntimeException("User not found with id: " + id));
            
            String oldData = toJson(user);
            System.out.println("=== UserService: Found user to delete: " + user.getName() + " ===");
            
            userRepository.deleteById(id);
            System.out.println("=== UserService: User deleted from repository ===");
            
            // TODO: Fix audit creation - temporarily disabled  
            // Audit audit = new Audit(null, id, "DELETE", oldData, null, null);
            // auditRepository.save(audit);
            System.out.println("=== UserService: Audit record created for deletion ===");
        } catch (Exception e) {
            System.err.println("=== UserService: Error during user deletion: " + e.getMessage() + " ===");
            e.printStackTrace();
            throw new RuntimeException("Failed to delete user: " + e.getMessage(), e);
        }
    }

    private String toJson(Object obj) {
        try {
            return objectMapper.writeValueAsString(obj);
        } catch (Exception e) {
            return "{}";
        }
    }
}
